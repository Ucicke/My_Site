/* Состав комнаты по её типу */
function roomComposition(roomType) {
    const size = roomType === 'ELITE'
        ? randIntIn('loot', 5, 6)
        : roomType === 'TREASURE' || roomType === 'DIG'
            ? randIntIn('loot', 3, 4)
            : randIntIn('loot', 3, 5);
    const variants = ROOM_COMPOSITIONS[size] || ROOM_COMPOSITIONS[3];
    const c = variants[randIntIn('loot', 0, variants.length - 1)];
    return { relic: c[0], mimic: c[1], empty: c[2], total: size };
}

